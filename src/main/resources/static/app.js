var esc = function (s) {
  return String(s).replace(/[&<>"]/g, function (c) {
    return { '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;' }[c];
  });
};
var pick = function (o) { return o ? (o[lang] || o.ko) : ''; };
var $ = function (sel, root) { return (root || document).querySelector(sel); };
var $$ = function (sel, root) { return Array.prototype.slice.call((root || document).querySelectorAll(sel)); };

/* style-hover: apply the attribute's declarations while hovered, restore on leave */
function bindHover(root) {
  $$('[style-hover]', root).forEach(function (el) {
    if (el.__hoverBound) return;
    el.__hoverBound = true;
    el.addEventListener('mouseenter', function () {
      el.__baseStyle = el.getAttribute('style') || '';
      el.setAttribute('style', el.__baseStyle + ';' + el.getAttribute('style-hover'));
    });
    el.addEventListener('mouseleave', function () {
      el.setAttribute('style', el.__baseStyle || '');
    });
  });
}

