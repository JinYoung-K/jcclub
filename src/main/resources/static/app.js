function goSlide(i) {
  var n = slides.length;
  slide = ((i % n) + n) % n;
  slides.forEach(function (el, k) {
    el.style.opacity = k === slide ? '1' : '0';
    el.style.zIndex = k === slide ? '5' : '0';
    el.style.pointerEvents = k === slide ? 'auto' : 'none';
  });
  dots.forEach(function (el, k) {
    el.style.width = k === slide ? '32px' : '10px';
    el.style.background = k === slide ? '#ffffff' : 'rgba(255,255,255,0.45)';
  });
}

function startAutoplay() {
  clearInterval(heroTimer);
  heroTimer = setInterval(function () { goSlide(slide + 1); }, 6000);
}

